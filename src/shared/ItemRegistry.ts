export function findSpliceResult(seedA: number, seedB: number): ItemDefinition | undefined {
  if (seedA === seedB) return undefined;
  const match = SPLICE_RECIPES.find(
    (r) =>
      (r.seedA === seedA && r.seedB === seedB) ||
      (r.seedA === seedB && r.seedB === seedA)
  );
  return match ? ITEM_MAP.get(match.resultSeedId) : undefined;
}

